# SQUARE BRACKETS []

# List - access by index (position)
my_list = ['apple', 'banana', 'orange']
print(my_list[0])  # Output: apple

# Dictionary - access by key
my_dict = {'trackName': 'Buddah', 'artistName': 'Weezer'}
print(my_dict['trackName'])  # Output: Buddah

# String - access by position
my_string = "hello"
print(my_string[0])  # Output: h

# PARENTHESES ()

# Function call
print("Hello")  # () calls the print function

# Tuple
my_tuple = (1, 2, 3)
print(my_tuple)  # Output: (1, 2, 3)

# Grouping
result = (5 + 3) * 2  # Parentheses force order of operations
print(result)  # Output: 16

# CURLY BRACKETS {}

# Dictionary
my_dict = {'name': 'John', 'age': 30}
print(my_dict)  # Output: {'name': 'John', 'age': 30}

# Set
my_set = {1, 2, 3}
print(my_set)  # Output: {1, 2, 3}

# F-string
name = "Weezer"
print(f"Artist: {name}")  # Output: Artist: Weezer
